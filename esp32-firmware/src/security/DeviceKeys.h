struct DeviceKeys {
    uint8_t devId[8];
    uint8_t kAuth[32];
    uint8_t kRec[32];
    uint8_t kSig[32];
    bool hasRec, hasSig;
};

enum class KeySource : uint8_t { Partition, DevFixed, MacDerived, Missing };

inline const char* keySourceName(KeySource s) {
    switch (s) {
        case KeySource::Partition: return "partition";
        case KeySource::DevFixed: return "dev_fixed";
        case KeySource::MacDerived: return "mac";
        default: return "missing";
    }
}

